"""Палитра приложения.

Категория хранит НЕ hex, а номер слота палитры (0..7). Причина: у слота два
значения — для светлой и тёмной темы. Хранили бы hex — в тёмной теме цвета,
подобранные под белый фон, теряли бы контраст, и починить это можно было бы
только миграцией данных.

Порядок слотов не случайный: это проверенная последовательность, у которой
соседние пары различимы при основных видах дальтонизма (worst adjacent
CVD ΔE 9.1 при пороге 8). Менять порядок или добавлять девятый цвет «на глаз»
нельзя — пропадёт различимость. Категории сверх восьми в графиках
сворачиваются в «Остальное».
"""

from __future__ import annotations

from typing import Final

# (светлая тема, тёмная тема, человекочитаемое имя)
PALETTE: Final[tuple[tuple[str, str, str], ...]] = (
    ("#2a78d6", "#3987e5", "Синий"),
    ("#eb6834", "#d95926", "Оранжевый"),
    ("#1baf7a", "#199e70", "Бирюзовый"),
    ("#eda100", "#c98500", "Жёлтый"),
    ("#e87ba4", "#d55181", "Розовый"),
    ("#008300", "#008300", "Зелёный"),
    ("#4a3aa7", "#9085e9", "Фиолетовый"),
    ("#e34948", "#e66767", "Красный"),
)

SLOT_COUNT: Final[int] = len(PALETTE)

# Нейтральный серый: операции без категории и свёртка «Остальное».
NEUTRAL_LIGHT: Final[str] = "#898781"
NEUTRAL_DARK: Final[str] = "#898781"


def slot_hex(slot: int | None, dark: bool = False) -> str:
    """Hex для слота. None или выход за диапазон — нейтральный серый."""
    if slot is None or not 0 <= slot < SLOT_COUNT:
        return NEUTRAL_DARK if dark else NEUTRAL_LIGHT
    return PALETTE[slot][1] if dark else PALETTE[slot][0]
